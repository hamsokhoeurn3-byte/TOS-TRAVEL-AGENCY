            $hotels,
            fn (array $hotel): bool => $hotel['price_level'] !== 'budget'
                || in_array($hotel['slug'], $keptBudgetSlugs, true),
        ));

        foreach ($hotels as $hotel) {
            $existingId = DB::table('hotels')
                ->where('slug', $hotel['slug'])
                ->value('id');

            $record = [
                'slug' => $hotel['slug'],
                'name' => $hotel['name'],
                'area' => $hotel['area'],
                'description' => $hotel['description'],
                'price_level' => $hotel['price_level'],
                'price_from' => $hotel['price_from'],
                'rating' => $hotel['rating'],
                'style' => $hotel['style'],
                'image_url' => '/hotels/'.$hotel['slug'].'/hotel/'.($hotel['image_filename'] ?? 'main.jpeg'),
                'room_types' => json_encode($hotel['room_types']),
                'website_url' => $hotel['website_url'],
                'sort_order' => $hotel['sort_order'],
            ];

            if ($existingId) {
                DB::table('hotels')
                    ->where('id', $existingId)
                    ->update($record);
            } else {
                DB::table('hotels')->insert([
                    'id' => (string) Str::uuid(),
                    ...$record,
                    'created_at' => now(),
                ]);
            }
        }

        $this->command?->info(
            'Successfully imported '.count($hotels).' hotels.'
        );
    }
}
